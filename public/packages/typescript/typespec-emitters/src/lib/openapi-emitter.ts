// OpenAPI `x-d2-*` extension emitter.
//
// The HTTP shape comes VERBATIM from the genuine stock `@typespec/openapi3`
// emitter via its programmatic `getOpenAPI3(program, options)` API — this file
// reimplements NONE of the OpenAPI document construction (no paths/schemas/
// components are built here). The only thing this emitter adds is the four
// `x-d2-*` vendor extensions that stock OpenAPI cannot express, read directly
// from the `@d2*` decorator stateMaps (the SAME reads the route-policy emitter
// performs), plus a document-level `x-d2-generated-by` traceability marker.
//
//   `x-d2-scope`    ← @d2RequireAnyScope / @d2RequireAllScopes / @d2Harmless
//                     (structured `{ mode, scopes }`, mirroring the route
//                     emitter's ScopePolicy so the OpenAPI doc and the C# route
//                     agree on the SAME auth intent).
//   `x-d2-tier`     ← @d2RateLimitTier (flat string).
//   `x-d2-csrf`     ← @d2Csrf (flat string).
//   `x-d2-audience` ← @d2Audience (flat string; per-op when the op declares it).
//
// An op→OpenAPI-operation correlation is built from `@typespec/http`'s
// `getAllHttpServices` (a `(verb, path) → Operation` index) and matched against
// the OpenAPI document's `paths` keys — both are produced by the same HTTP
// library walk, so the keys align. An op with no auth intent never reaches a
// valid emitted document (the route-policy emitter fails the same compile with
// D2TSP004); the no-auth-intent branch here is defensive only.
//
// Output is JSON, which has no comment syntax, so there is no `//` banner
// (mirrors the smoke manifest). Determinism: the stock document is a pure
// function of the program, and the four `x-d2-*` keys are appended in a fixed
// order, so the serialized bytes are stable across regenerations (the byte gate
// depends on this).

import { getAllHttpServices } from "@typespec/http";
import { listServices } from "@typespec/compiler";
import type { Operation, Program } from "@typespec/compiler";
import { getOpenAPI3 } from "@typespec/openapi3";
import type { OpenAPI3Document, OpenAPI3Operation } from "@typespec/openapi3";
import {
  D2_REQUIRE_ANY_SCOPE_KEY,
  D2_REQUIRE_ALL_SCOPES_KEY,
  D2_HARMLESS_KEY,
  D2_RATE_LIMIT_TIER_KEY,
  D2_AUDIENCE_KEY,
  D2_CSRF_KEY,
} from "@dcsv-io/d2-typespec-decorators";
import type { EmittedFile } from "./csharp-dto-emitter.js";

export type { EmittedFile } from "./csharp-dto-emitter.js";

// ---------------------------------------------------------------------------
// Public types
// ---------------------------------------------------------------------------

/**
 * The structured `x-d2-scope` extension value. Mirrors the route-policy
 * emitter's `ScopePolicy` (any / all / harmless) so the emitted OpenAPI
 * document and the generated C# route registration encode the identical auth
 * intent for the same operation.
 */
export type D2ScopeExtension =
  | { readonly mode: "any"; readonly scopes: readonly string[] }
  | { readonly mode: "all"; readonly scopes: readonly string[] }
  | { readonly mode: "harmless" };

/**
 * The doc-level `x-d2-generated-by` traceability marker. JSON has no comment
 * channel for the standard `// Generated by …` banner, so the provenance lives
 * inside the document's own legal extension surface.
 */
export interface D2GeneratedByExtension {
  readonly emitter: string;
  readonly note: string;
}

/**
 * The OpenAPI 3.0 HTTP methods a path item can carry. This is the fixed,
 * spec-defined verb set (not a spec-mirror data shape) — used to key into the
 * stock document's path items. `@typespec/openapi3` does not re-export its
 * `OpenAPI3HttpMethod` type through the package barrel, so the verb literals are
 * declared here.
 */
export type OpenApiHttpMethod =
  | "get"
  | "put"
  | "post"
  | "delete"
  | "options"
  | "head"
  | "patch"
  | "trace";

/** The emitter name recorded in the `x-d2-generated-by` document extension. */
export const OPENAPI_GENERATED_BY_EMITTER = "@dcsv-io/d2-typespec-emitters";

/** The note recorded in the `x-d2-generated-by` document extension. */
export const OPENAPI_GENERATED_BY_NOTE =
  "x-d2-* policy extensions layered on the stock @typespec/openapi3 document. Manual edits will be lost on rebuild.";

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/**
 * Inject the four `x-d2-*` per-operation extensions plus the document-level
 * `x-d2-generated-by` marker into one stock OpenAPI document, reading the
 * policy from the `@d2*` decorator stateMaps.
 *
 * Pure over the document: mutates the supplied document in place and returns it
 * (the stock document object is owned by the caller for this version). The
 * HTTP shape is untouched — only `x-`-prefixed extension keys are added.
 *
 * @param program  - The compiled TypeSpec program (the stateMap source).
 * @param document - One OpenAPI 3.0 document produced by `getOpenAPI3`.
 * @returns The same document with the `x-d2-*` extensions applied.
 */
export function injectD2Extensions(
  program: Program,
  document: OpenAPI3Document,
): OpenAPI3Document {
  // Document-level provenance marker (fixed first so it appears deterministically).
  const generatedBy: D2GeneratedByExtension = {
    emitter: OPENAPI_GENERATED_BY_EMITTER,
    note: OPENAPI_GENERATED_BY_NOTE,
  };
  document["x-d2-generated-by"] = generatedBy;

  // Build the (verb, path) → TypeSpec Operation index from the SAME HTTP-library
  // walk the stock emitter used to produce the document's paths, so the keys
  // align. Diagnostics from this read are ignored here — a malformed HTTP
  // binding would already have failed the compile via the route-policy emitter.
  const opIndex = buildOperationIndex(program);

  for (const [path, pathItem] of Object.entries(document.paths)) {
    for (const method of HTTP_METHODS) {
      const operation = pathItem[method];
      if (operation === undefined) continue;

      const tspOp = opIndex.get(indexKey(method, path));
      // A path-item operation with no matching TypeSpec op (e.g. a synthetic
      // entry) carries no `@d2*` state — skip injection for it.
      if (tspOp === undefined) continue;

      injectOperationExtensions(program, tspOp, operation);
    }
  }

  return document;
}

/**
 * Run the genuine stock `@typespec/openapi3` emitter against the program and
 * return one emitted OpenAPI file per (service × service-version), each with the
 * `x-d2-*` extensions injected.
 *
 * Handles BOTH `OpenAPI3ServiceRecord` arms: the unversioned arm (one
 * `document`) and the versioned arm (one `document` per version, the file name
 * carrying the version segment). The HTTP shape is produced entirely by
 * `getOpenAPI3` — this function only post-processes each returned document
 * object and serializes it.
 *
 * @param program - The compiled TypeSpec program.
 * @returns One {@link EmittedFile} per service×version. Empty when no
 *   `@service` namespace exists (the stock emitter returns no records).
 */
export async function emitOpenApiDocuments(
  program: Program,
): Promise<EmittedFile[]> {
  // Emit only when the program declares at least one @service namespace; this
  // prevents getOpenAPI3 from triggering the @typespec/http `no-service-found`
  // warning for routed-but-serviceless fixture programs (which would otherwise
  // pollute the compile's diagnostics).
  if (listServices(program).length === 0) return [];

  // Default OpenAPI spec version (3.0.0) — the stock document is the 3.0.0
  // `OpenAPI3Document` arm. No `file-type` / `output-file` / `new-line` options
  // (the serialization here is the emitter's responsibility per §26.5).
  const records = await getOpenAPI3(program);

  const files: EmittedFile[] = [];
  for (const record of records) {
    const serviceName = resolveServiceName(record.service.type.name);

    if (record.versioned) {
      for (const versioned of record.versions) {
        const document = injectD2Extensions(
          program,
          versioned.document as OpenAPI3Document,
        );
        files.push({
          fileName: openApiFileName(serviceName, versioned.version),
          content: serializeDocument(document),
        });
      }
    } else {
      const document = injectD2Extensions(
        program,
        record.document as OpenAPI3Document,
      );
      files.push({
        fileName: openApiFileName(serviceName, undefined),
        content: serializeDocument(document),
      });
    }
  }

  return files;
}

// ---------------------------------------------------------------------------
// Internal helpers
// ---------------------------------------------------------------------------

/** The HTTP methods an OpenAPI 3.0 path item can carry, in a fixed walk order. */
const HTTP_METHODS: readonly OpenApiHttpMethod[] = [
  "get",
  "put",
  "post",
  "delete",
  "options",
  "head",
  "patch",
  "trace",
];

/** Build the `(verb, path)` index key. */
function indexKey(verb: string, path: string): string {
  return `${verb} ${path}`;
}

/**
 * Build a `(verb, path) → Operation` index from every HTTP operation in the
 * program. The path/verb pairs come from the same `getAllHttpServices` walk the
 * stock OpenAPI emitter uses, so the keys match the document's `paths` keys.
 */
function buildOperationIndex(program: Program): Map<string, Operation> {
  const index = new Map<string, Operation>();
  const [services] = getAllHttpServices(program);

  for (const service of services) {
    for (const httpOp of service.operations) {
      index.set(indexKey(httpOp.verb, httpOp.path), httpOp.operation);
    }
  }

  return index;
}

/**
 * Inject the four `x-d2-*` extensions onto one OpenAPI operation, reading the
 * auth/tier/audience/csrf policy from the TypeSpec op's `@d2*` stateMaps. Keys
 * are assigned in a fixed order (scope, tier, audience, csrf) for deterministic
 * serialization. An extension is omitted when its decorator is absent.
 */
function injectOperationExtensions(
  program: Program,
  tspOp: Operation,
  operation: OpenAPI3Operation,
): void {
  const scope = resolveScopeExtension(program, tspOp);
  // A routed op with no auth intent never reaches a valid emitted document
  // (the route-policy emitter fails the same compile with D2TSP004); guard
  // defensively so a state-less op simply carries no `x-d2-scope`.
  if (scope !== undefined) operation["x-d2-scope"] = scope;

  const tier = resolveTier(program, tspOp);
  if (tier !== undefined) operation["x-d2-tier"] = tier;

  const audience = program.stateMap(D2_AUDIENCE_KEY).get(tspOp) as
    | string
    | undefined;
  if (audience !== undefined) operation["x-d2-audience"] = audience;

  const csrf = resolveCsrf(program, tspOp);
  if (csrf !== undefined) operation["x-d2-csrf"] = csrf;
}

/**
 * Resolve the structured `x-d2-scope` value from the op's scope/harmless
 * stateMaps. Mirrors the route-policy emitter's ScopePolicy resolution exactly
 * (any → all → harmless), returning undefined when none is declared.
 */
function resolveScopeExtension(
  program: Program,
  op: Operation,
): D2ScopeExtension | undefined {
  const anyScopes = program.stateMap(D2_REQUIRE_ANY_SCOPE_KEY).get(op) as
    | string[]
    | undefined;
  const allScopes = program.stateMap(D2_REQUIRE_ALL_SCOPES_KEY).get(op) as
    | string[]
    | undefined;
  const harmless = program.stateMap(D2_HARMLESS_KEY).get(op) === true;

  if (anyScopes !== undefined && anyScopes.length > 0)
    return { mode: "any", scopes: anyScopes };
  if (allScopes !== undefined && allScopes.length > 0)
    return { mode: "all", scopes: allScopes };
  if (harmless) return { mode: "harmless" };

  return undefined;
}

/**
 * Resolve the flat `x-d2-tier` string. The decorator stores either a bare
 * string or a `{ tier }` payload (same shape the route-policy emitter reads).
 */
function resolveTier(program: Program, op: Operation): string | undefined {
  const raw = program.stateMap(D2_RATE_LIMIT_TIER_KEY).get(op) as
    | { tier: string }
    | string
    | undefined;
  if (raw === undefined) return undefined;

  return typeof raw === "string" ? raw : raw.tier;
}

/**
 * Resolve the flat `x-d2-csrf` posture string. The decorator stores either a
 * bare string or a `{ posture }` payload (same shape the route-policy emitter
 * reads).
 */
function resolveCsrf(program: Program, op: Operation): string | undefined {
  const raw = program.stateMap(D2_CSRF_KEY).get(op) as
    | { posture: string }
    | string
    | undefined;
  if (raw === undefined) return undefined;

  return typeof raw === "string" ? raw : raw.posture;
}

/**
 * Normalize a `@service` namespace name into a kebab file-name segment. An
 * unnamed service falls back to a stable placeholder so a file is still emitted.
 */
function resolveServiceName(name: string | undefined): string {
  if (name === undefined || name.length === 0) return "service";

  return toKebab(name);
}

/**
 * Build the emitted OpenAPI file name: `<service>.openapi.g.json` for an
 * unversioned service, `<service>.<version>.openapi.g.json` when versioned. The
 * version segment is kebab-normalized so it is filesystem-safe.
 */
function openApiFileName(
  serviceName: string,
  version: string | undefined,
): string {
  if (version === undefined || version.length === 0)
    return `${serviceName}.openapi.g.json`;

  return `${serviceName}.${toKebab(version)}.openapi.g.json`;
}

/**
 * Serialize an OpenAPI document to deterministic 2-space JSON with a trailing
 * newline (LF). Generated-output formatting is the emitter's responsibility
 * (never Prettier); the trailing newline matches the other emitters' fixtures.
 */
function serializeDocument(document: OpenAPI3Document): string {
  return JSON.stringify(document, null, 2) + "\n";
}

/**
 * Convert a PascalCase / dotted / spaced identifier to a lowercase kebab
 * segment (e.g. `KeyCustodian` → `key-custodian`, `My.Service v2` →
 * `my-service-v2`). Pure string transform; no I/O.
 */
function toKebab(value: string): string {
  return value
    .replace(/[.\s]+/g, "-")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[^a-zA-Z0-9-]/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();
}
