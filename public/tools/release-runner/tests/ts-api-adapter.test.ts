describe("diffApiMembers", () => {
  it("no change → all false", () => {
    const base = new Set([
      "export const A: string;",
      "export type B = number;",
    ]);
    const fresh = new Set([
      "export const A: string;",
      "export type B = number;",
    ]);

    expect(diffApiMembers(base, fresh)).toEqual({
      added: false,
      removed: false,
      changed: false,
    });
  });

  it("added member → added: true, others false", () => {
    const base = new Set(["export const A: string;"]);
    const fresh = new Set([
      "export const A: string;",
      "export const C: boolean;",
    ]);
    const result = diffApiMembers(base, fresh);

    expect(result.added).toBe(true);
    expect(result.removed).toBe(false);
    expect(result.changed).toBe(false);
  });

  it("removed member → removed: true, others false", () => {
    const base = new Set([
      "export const A: string;",
      "export const B: number;",
    ]);
    const fresh = new Set(["export const A: string;"]);
    const result = diffApiMembers(base, fresh);

    expect(result.added).toBe(false);
    expect(result.removed).toBe(true);
    expect(result.changed).toBe(false);
  });

  it("changed member signature (same name, different type) → changed: true", () => {
    const base = new Set(["export const A: string;"]);
    const fresh = new Set(["export const A: number;"]);
    const result = diffApiMembers(base, fresh);

    expect(result.added).toBe(false);
    expect(result.removed).toBe(false);
    expect(result.changed).toBe(true);
  });

  it("rename (old removed, new added) → added:true + removed:true, changed:false", () => {
    const base = new Set(["export const OldName: string;"]);
    const fresh = new Set(["export const NewName: string;"]);
    const result = diffApiMembers(base, fresh);

    expect(result.added).toBe(true);
    expect(result.removed).toBe(true);
    expect(result.changed).toBe(false);
  });

  it("empty baseline + one member fresh → added:true only", () => {
    const result = diffApiMembers(
      new Set(),
      new Set(["export const X: string;"]),
    );

    expect(result.added).toBe(true);
    expect(result.removed).toBe(false);
    expect(result.changed).toBe(false);
  });

  it("one member baseline + empty fresh → removed:true only", () => {
    const result = diffApiMembers(
      new Set(["export const X: string;"]),
      new Set(),
    );

    expect(result.added).toBe(false);
    expect(result.removed).toBe(true);
    expect(result.changed).toBe(false);
  });

  it("both removed and added simultaneously → removed:true + added:true", () => {
    const base = new Set([
      "export const A: string;",
      "export const B: number;",
    ]);
    const fresh = new Set([
      "export const A: string;",
      "export const C: boolean;",
    ]);
    const result = diffApiMembers(base, fresh);

    expect(result.added).toBe(true);
    expect(result.removed).toBe(true);
    expect(result.changed).toBe(false);
  });
});

