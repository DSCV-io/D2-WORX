// The git-ref apiDiff + source-based fingerprint composition are covered in
// real-diff-provider.test.ts. The real api-extractor runner is exercised by the
// gated CI lane (`.api.md` currency gate); an ESM-require regression test pins
// that it resolves under a plain ESM (tsx) process.

