describe("parseApiMembers — fence extraction", () => {
  it("parses a simple single-line export const", () => {
    const md = `\`\`\`ts\n\n// @public\nexport const FOO: string;\n\n\`\`\`\n`;
    const members = parseApiMembers(md);
    expect(members.has("export const FOO: string;")).toBe(true);
    expect(members.size).toBe(1);
  });

  it("parses a single-line export type alias", () => {
    const md = `\`\`\`ts\n\n// @public\nexport type Cat = "a" | "b";\n\n\`\`\`\n`;
    const members = parseApiMembers(md);
    expect(members.has(`export type Cat = "a" | "b";`)).toBe(true);
  });

  it("parses a multi-line export const object", () => {
    const md =
      `\`\`\`ts\n\n// @public\nexport const Wire: {\n` +
      `    readonly A: "a";\n    readonly B: "b";\n};\n\n\`\`\`\n`;
    const members = parseApiMembers(md);
    expect(members.size).toBe(1);
    const decl = [...members][0]!;
    expect(decl).toContain("export const Wire:");
    expect(decl).toContain(`readonly A: "a";`);
  });

  it("excludes comment lines and blank lines at top level", () => {
    const md = `\`\`\`ts\n\n// @public\nexport const X: number;\n\n// (No @packageDocumentation comment for this package)\n\n\`\`\`\n`;
    const members = parseApiMembers(md);
    expect(members.size).toBe(1);
    expect([...members][0]).toBe("export const X: number;");
  });

  it("handles content before the fence (ignores it)", () => {
    const md = `# Header\nSome prose\n\n\`\`\`ts\n\n// @public\nexport function foo(): void;\n\n\`\`\`\n`;
    const members = parseApiMembers(md);
    expect(members.has("export function foo(): void;")).toBe(true);
  });

  it("returns empty set for an api.md with no exports", () => {
    const md = `\`\`\`ts\n\n// (No @packageDocumentation comment for this package)\n\n\`\`\`\n`;
    const members = parseApiMembers(md);
    expect(members.size).toBe(0);
  });

  it("parses the representative baseline: 3 members", () => {
    const members = parseApiMembers(BASELINE_API_MD);
    expect(members.size).toBe(3);
    expect(
      members.has(
        "export const ALL_ERROR_CATEGORIES: readonly ErrorCategory[];",
      ),
    ).toBe(true);

    const wireDecl = [...members].find((m) =>
      m.startsWith("export const ErrorCategoryWire:"),
    );

    expect(wireDecl).toBeDefined();
  });
});

