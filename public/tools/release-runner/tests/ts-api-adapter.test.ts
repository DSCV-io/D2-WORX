// Tests for the TS extraction helpers (ts-api-adapter.ts) — pure, build-free:
//   - parseApiMembers: fence extraction, multi-line declarations
//   - extractMemberName: identifier extraction per declaration kind
//   - diffApiMembers: added / removed / changed detection
//   - resolveApiMdPath: basename-vs-reportFileName resolution
//   - tsFingerprintBaselinePath: etc/.release-fingerprint
