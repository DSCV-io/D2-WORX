describe("extractMemberName", () => {
  it("extracts name from export const", () => {
    expect(extractMemberName("export const FOO: string;")).toBe("FOO");
  });

  it("extracts name from export type", () => {
    expect(extractMemberName("export type MyType = string;")).toBe("MyType");
  });

  it("extracts name from export function", () => {
    expect(extractMemberName("export function doThing(): void;")).toBe(
      "doThing",
    );
  });

  it("extracts name from export class", () => {
    expect(extractMemberName("export class Foo {")).toBe("Foo");
  });

  it("extracts name from export interface", () => {
    expect(extractMemberName("export interface IBar {")).toBe("IBar");
  });

  it("extracts name from export enum", () => {
    expect(extractMemberName("export enum Status {")).toBe("Status");
  });

  it("falls back to first line for unrecognised pattern", () => {
    expect(extractMemberName("export default something;")).toBe(
      "export default something;",
    );
  });

  it("extracts name from multi-line decl (uses first line only)", () => {
    const decl = `export const Wire: {\n    readonly A: "a";\n};`;
    expect(extractMemberName(decl)).toBe("Wire");
  });
});

