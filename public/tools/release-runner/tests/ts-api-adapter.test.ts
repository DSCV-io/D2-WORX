/** A representative committed baseline api.md content. */
const BASELINE_API_MD = `## API Report File for "@d2/error-category"

> Do not edit this file. It is a report generated by [API Extractor](https://api-extractor.com/).

\`\`\`ts

// @public
export const ALL_ERROR_CATEGORIES: readonly ErrorCategory[];

// @public
export type ErrorCategory = "conflict" | "internal_error";

// @public
export const ErrorCategoryWire: {
    readonly Conflict: "conflict";
    readonly InternalError: "internal_error";
};

// (No @packageDocumentation comment for this package)

\`\`\`
`;

