namespace DcsvIo.D2.Private.Edge.KeyCustodian.ErrorCodes.SourceGen;

using System;
using DcsvIo.D2.ErrorCodes.SourceGen;
using Microsoft.CodeAnalysis;

/// <summary>
/// Roslyn incremental source generator that emits the
/// <c>KeyCustodianErrorCodes</c> constants class + the
/// <c>KeyCustodianFailures</c> factory class into
/// <c>DcsvIo.D2.Private.Edge.KeyCustodian.Domain</c> by reading
/// <c>contracts/keycustodian-error-codes/keycustodian-error-codes.spec.json</c>
/// via <c>AdditionalFiles</c>. A thin shell over the shared
/// <see cref="ErrorCodesEngine"/> — it owns only the keycustodian catalog's
/// identity (assembly name + this type's FQN, both load-bearing for the
/// on-disk generated path) + its <see cref="CatalogConfig"/>; all generation
/// logic lives in the shared engine. Single-target — only emits when the
/// consuming assembly is <c>DcsvIo.D2.Private.Edge.KeyCustodian.Domain</c>.
/// </summary>
[Generator]
public sealed class ErrorCodesGenerator : IIncrementalGenerator
{
    private const string _CONSTANTS_BANNER =
        "// -----------------------------------------------------------------------\n" +
        "// <auto-generated>\n" +
        "//   Generated by DcsvIo.D2.Private.Edge.KeyCustodian.ErrorCodes.SourceGen.ErrorCodesGenerator\n" +
        "//   from contracts/keycustodian-error-codes/keycustodian-error-codes.spec.json\n" +
        "//   (the source of truth). Manual edits will be lost on rebuild.\n" +
        "// </auto-generated>\n" +
        "// -----------------------------------------------------------------------\n";

    private const string _FAILURES_BANNER = _CONSTANTS_BANNER;

    private const string _CONSTANTS_SUMMARY =
        "/// <summary>\n" +
        "/// Machine-readable <c>d2_error_code</c> string constants surfaced on\n" +
        "/// <see cref=\"DcsvIo.D2.Result.D2Result\"/> failures + RFC 7807\n" +
        "/// <c>ProblemDetails.Extensions[\"d2_error_code\"]</c>.\n" +
        "/// </summary>\n" +
        "/// <remarks>\n" +
        "/// Generated from the spec file - drift between the codes here and the\n" +
        "/// merged error-code registry is impossible (the registry SrcGen consumes\n" +
        "/// the same spec via glob discovery).\n" +
        "/// </remarks>\n";

    private const string _ALL_CODES_DOC =
        "    /// <summary>\n" +
        "    /// All declared <c>KEYCUSTODIAN_*</c> codes in spec order. Useful for\n" +
        "    /// registry membership checks and cross-spec consistency tests.\n" +
        "    /// </summary>\n";

    private const string _GET_HTTP_STATUS_DOC =
        "    /// <summary>\n" +
        "    /// Returns the HTTP status code declared in the spec for\n" +
        "    /// <paramref name=\"errorCode\"/>, or <c>500</c> if the code is not\n" +
        "    /// recognized (defensive default - every shipped <c>KEYCUSTODIAN_*</c>\n" +
        "    /// code is in the table).\n" +
        "    /// </summary>\n" +
        "    /// <param name=\"errorCode\">The keycustodian error code.</param>\n" +
        "    /// <returns>The HTTP status code.</returns>\n";

    private const string _FAILURES_SUMMARY =
        "/// <summary>\n" +
        "/// Pre-built <see cref=\"D2Result\"/> failures for the KeyCustodian domain -\n" +
        "/// key-identifier validation, key-domain catalog membership, rotation-policy\n" +
        "/// invariants, and the soak / smoke-proof / grace transition guards.\n" +
        "/// </summary>\n" +
        "/// <remarks>\n" +
        "/// Two-axis design: coarse user-facing TK key (per status bucket) plus\n" +
        "/// granular machine-readable <see cref=\"KeyCustodianErrorCodes\"/> constant.\n" +
        "/// Generated from the spec file - drift between the factory list and the\n" +
        "/// <see cref=\"KeyCustodianErrorCodes\"/> constants is impossible (single spec\n" +
        "/// source).\n" +
        "/// </remarks>\n";

    private const string _GENERIC_FAILURES_SUMMARY =
        "/// <summary>\n" +
        "/// Typed twin of <see cref=\"KeyCustodianFailures\"/> - pre-built\n" +
        "/// <see cref=\"D2Result{T}\"/> KeyCustodian failures for callers that need a\n" +
        "/// typed result (e.g. <c>KeyCustodianFailures&lt;Kid&gt;.KidInvalid()</c>).\n" +
        "/// Identical method names to the non-generic class; each delegates to the\n" +
        "/// typed <see cref=\"D2Result{T}\"/> base factory, stamping the same\n" +
        "/// <see cref=\"KeyCustodianErrorCodes\"/> constant + user-facing TK key.\n" +
        "/// </summary>\n" +
        "/// <remarks>\n" +
        "/// <see cref=\"KeyCustodianFailures\"/> (non-generic) and\n" +
        "/// <c>KeyCustodianFailures&lt;T&gt;</c> (generic) are distinct types (arity\n" +
        "/// differs) - exactly as <see cref=\"D2Result\"/> / <see cref=\"D2Result{T}\"/>\n" +
        "/// coexist. Generated from the spec file (single source).\n" +
        "/// </remarks>\n";

    private static readonly CatalogConfig sr_config = new(
        TargetAssemblyName: "DcsvIo.D2.Private.Edge.KeyCustodian.Domain",
        SpecFileName: "keycustodian-error-codes.spec.json",
        RootNamespace: "DcsvIo.D2.Private.Edge.KeyCustodian.Domain.Errors",
        ConstantsClassName: "KeyCustodianErrorCodes",
        ConstantsSourceName: "KeyCustodianErrorCodes.g.cs",
        ConstantsBanner: _CONSTANTS_BANNER,
        ConstantsSummary: _CONSTANTS_SUMMARY,
        AllCodesDoc: _ALL_CODES_DOC,
        GetHttpStatusDoc: _GET_HTTP_STATUS_DOC,
        DomainPrefix: "KEYCUSTODIAN_",
        EmitKebabCase: false,
        EmitFailures: true,
        FailuresClassName: "KeyCustodianFailures",
        FailuresSourceName: "KeyCustodianFailures.g.cs",
        FailuresBanner: _FAILURES_BANNER,
        FailuresSummary: _FAILURES_SUMMARY,
        ValidateCategory: true,
        MalformedSpecId: DiagnosticIds.MalformedSpec,
        DuplicateCodeId: DiagnosticIds.DuplicateCode,
        InvalidHttpStatusId: DiagnosticIds.InvalidHttpStatus,
        InvalidCodeId: null,
        MissingDocId: null,
        UnknownCategoryId: DiagnosticIds.UnknownCategoryEnum,
        DuplicateFactoryNameId: DiagnosticIds.DuplicateFactoryName,
        FactoryHost: FactoryHost.Domain,
        GenericFailuresSourceName: "KeyCustodianFailures.Generic.g.cs",
        GenericFailuresSummary: _GENERIC_FAILURES_SUMMARY,
        MessageKeyClassName: "ProductTK",
        MessageKeyUsingNamespace: "DcsvIo.D2.Private.I18n");

    /// <summary>
    /// Gets the keycustodian catalog configuration. Exposed for unit tests that
    /// drive the shared engine emitters directly with the real catalog config.
    /// </summary>
    internal static CatalogConfig Config => sr_config;

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context) =>
        ErrorCodesEngine.Run(context, sr_config, ResolveDescriptor);

    private static DiagnosticDescriptor ResolveDescriptor(string id) => id switch
    {
        DiagnosticIds.MalformedSpec => DiagnosticDescriptors.MalformedSpec,
        DiagnosticIds.UnknownCategoryEnum => DiagnosticDescriptors.UnknownCategoryEnum,
        DiagnosticIds.DuplicateCode => DiagnosticDescriptors.DuplicateCode,
        DiagnosticIds.DuplicateFactoryName => DiagnosticDescriptors.DuplicateFactoryName,
        DiagnosticIds.InvalidHttpStatus => DiagnosticDescriptors.InvalidHttpStatus,
        _ => throw new InvalidOperationException(
            $"Unknown EmitDiagnostic descriptor id '{id}'."),
    };
}
