namespace D2.Tools.LoggerMessageSplitter;

/// <summary>
/// Parses a combined Microsoft.Extensions.Logging.Generators-emitted
/// LoggerMessage.g.cs file into one deterministic per-class file per
/// partial class. Brace-depth state machine; no Roslyn dependency.
///
/// Input format (verified against v10.0.14.21808 emitter output):
///
///   // <auto-generated/>
///   #nullable enable
///
///   namespace D2.X.Y { partial class FooLog { ... } }
///   namespace D2.A.B { partial class BarLog { ... } }
///   ...
///
/// Output format: one file per `(namespace, class)` tuple, named
///   LoggerMessage.{NamespaceLastSegment}.{ClassName}.g.cs
/// Each file carries the same header (`// <auto-generated/>` +
/// `#nullable enable` + a blank line) followed by a single
/// `namespace X { partial class Y { ... } }` block.
///
/// Determinism:
/// - Filenames are deterministic from (namespace last segment, class name).
/// - File content carries the SINGLE class block — no cross-class ordering
///   inside any file.
/// - The combined input's block-order does not affect any individual output
///   file's content.
/// - Stale per-class files in the output directory that don't correspond to
///   a class in the current input are deleted on each run.
/// </summary>
internal static class SplitterEngine
{
    /// <summary>Cached SearchValues for class-name terminator scan (CA1870).</summary>
    private static readonly System.Buffers.SearchValues<char> sr_classNameTerminators =
        System.Buffers.SearchValues.Create([' ', '\t', '{', '<', ':', '\r']);

    /// <summary>
    /// Pure (in-memory) parse + emit. Used by tests; the CLI shells around this.
    /// </summary>
    /// <param name="input">Full text of the combined LoggerMessage.g.cs file.</param>
    /// <returns>
    /// Map from per-class output filename to per-class file content. Caller
    /// writes to disk + handles stale-file cleanup.
    /// </returns>
    public static IReadOnlyDictionary<string, string> Split(string input)
    {
        var blocks = ParseBlocks(input);
        var output = new SortedDictionary<string, string>(StringComparer.Ordinal);

        foreach (var block in blocks)
        {
            var filename = $"LoggerMessage.{block.NamespaceLastSegment}.{block.ClassName}.g.cs";
            var content = ComposeFile(block);

            // Deterministic order via SortedDictionary; duplicate keys (same
            // namespace+class appearing twice) are an emitter bug — fail loud
            // rather than silently overwriting.
            if (output.ContainsKey(filename))
                throw new InvalidOperationException(
                    $"Duplicate (namespace, class) tuple in input: '{block.Namespace}.{block.ClassName}'. " +
                    $"Suggests the generator emitted two partial-class blocks for the same target — investigate.");

            output.Add(filename, content);
        }

        return output;
    }

    /// <summary>
    /// Disk-writing wrapper around <see cref="Split(string)"/>. Writes per-class
    /// files into <paramref name="outputDir"/> and deletes any stale per-class
    /// files (matching the splitter's naming pattern) that are not in the
    /// current emit set. Idempotent: re-runs against unchanged input produce
    /// no disk changes.
    /// </summary>
    /// <param name="inputPath">Absolute path to the combined LoggerMessage.g.cs.</param>
    /// <param name="outputDir">Absolute path to the directory to write split files into.</param>
    /// <returns>
    /// Number of split files written (including up-to-date no-op writes,
    /// which short-circuit so they don't update mtime).
    /// </returns>
    public static int Run(string inputPath, string outputDir)
    {
        var input = File.ReadAllText(inputPath);
        var splitFiles = Split(input);

        Directory.CreateDirectory(outputDir);

        // Pass 1: write per-class files. Skip writes when content is byte-identical
        // so we don't update mtime (which would re-trigger downstream incremental
        // build steps unnecessarily).
        foreach (var (filename, content) in splitFiles)
        {
            var path = Path.Combine(outputDir, filename);
            if (File.Exists(path))
            {
                var existing = File.ReadAllText(path);
                if (string.Equals(existing, content, StringComparison.Ordinal))
                    continue;
            }

            File.WriteAllText(path, content);
        }

        // Pass 2: delete stale per-class files that don't appear in the current
        // emit set. Scope is restricted to files matching the splitter's exact
        // naming pattern so we never collide with the combined input file itself
        // or any other generator's output that might land in the same directory.
        var expectedNames = new HashSet<string>(splitFiles.Keys, StringComparer.Ordinal);

        foreach (var existingPath in Directory.GetFiles(outputDir, "LoggerMessage.*.g.cs"))
        {
            var name = Path.GetFileName(existingPath);
            // Skip the combined input file itself (LoggerMessage.g.cs has no
            // intermediate segment so wouldn't match "LoggerMessage.*.*.g.cs" —
            // but be belt-and-braces in case the input path resolves into
            // outputDir).
            if (string.Equals(name, "LoggerMessage.g.cs", StringComparison.Ordinal))
                continue;

            if (!expectedNames.Contains(name))
                File.Delete(existingPath);
        }

        return splitFiles.Count;
    }

    private static List<ParsedBlock> ParseBlocks(string input)
    {
        var blocks = new List<ParsedBlock>();
        var lines = input.Split('\n');

        var i = 0;

        while (i < lines.Length)
        {
            var line = lines[i];
            var trimmed = line.TrimStart();

            if (trimmed.StartsWith("namespace ", StringComparison.Ordinal))
            {
                // Parse "namespace X.Y.Z" or "namespace X.Y.Z {" forms (the
                // emitter uses block-style consistently, but tolerate the brace
                // on the next line too).
                var nameStartIdx = trimmed.IndexOf(' ', StringComparison.Ordinal) + 1;
                var rest = trimmed[nameStartIdx..].TrimEnd('\r');
                var braceIdx = rest.IndexOf('{', StringComparison.Ordinal);
                var nsName = (braceIdx >= 0 ? rest[..braceIdx] : rest).Trim();

                // Find the namespace-opening brace (could be on same line or
                // next line(s)).
                var nsBraceLine = i;
                if (braceIdx < 0)
                {
                    while (++nsBraceLine < lines.Length)
                    {
                        if (lines[nsBraceLine].TrimStart().StartsWith('{'))
                            break;
                    }

                    if (nsBraceLine >= lines.Length)
                        throw new InvalidOperationException(
                            $"Malformed input: namespace declaration on line {i + 1} has no opening brace.");
                }

                // Inside the namespace block, scan for `partial class X` /
                // `partial sealed class X` / `partial static class X` etc.
                // Track brace depth so we can find each class's matching close
                // brace.
                var nsDepth = 1; // we've opened the namespace
                var j = nsBraceLine + 1;

                while (j < lines.Length && nsDepth > 0)
                {
                    var inner = lines[j];
                    var innerTrim = inner.TrimStart();

                    if (innerTrim.StartsWith("partial class ", StringComparison.Ordinal)
                        || ContainsPartialClass(innerTrim))
                    {
                        var (className, classCloseLine) = ParseClassBlock(lines, j);
                        var classBlockText = string.Join('\n', lines[j..(classCloseLine + 1)]);

                        var nsLast = nsName.Contains('.', StringComparison.Ordinal)
                            ? nsName[(nsName.LastIndexOf('.') + 1)..]
                            : nsName;

                        blocks.Add(new ParsedBlock(
                            Namespace: nsName,
                            NamespaceLastSegment: nsLast,
                            ClassName: className,
                            ClassBlockText: classBlockText));

                        j = classCloseLine + 1;
                        continue;
                    }

                    // Track brace depth outside of class bodies so we know
                    // when the namespace closes.
                    foreach (var ch in inner)
                    {
                        if (ch == '{') nsDepth++;
                        else if (ch == '}') nsDepth--;
                    }

                    if (nsDepth == 0)
                    {
                        // Found namespace close. Skip past it.
                        i = j + 1;
                        goto nextOuter;
                    }

                    j++;
                }

                i = j;
                continue;
            }

            i++;
        nextOuter:;
        }

        return blocks;
    }

    /// <summary>
    /// True if the trimmed line declares a partial class (with any combination
    /// of modifiers: `partial class`, `internal partial class`, `partial sealed
    /// class`, etc.). Token-based check so we don't false-match e.g. a string
    /// literal containing "partial class".
    /// </summary>
    private static bool ContainsPartialClass(string trimmed)
    {
        // Cheap token scan — split on whitespace and look for consecutive
        // "partial" then "class" tokens. The emitter only emits `partial class X`
        // and never decorates with extra modifiers, but be permissive in case
        // a future emitter version adds them.
        var tokens = trimmed.Split([' ', '\t'], StringSplitOptions.RemoveEmptyEntries);
        for (var k = 0; k < tokens.Length - 1; k++)
        {
            if (tokens[k] == "partial" && tokens[k + 1] == "class")
                return true;
        }

        return false;
    }

    /// <summary>
    /// Given a starting line that contains a `partial class X` declaration,
    /// finds the class's matching closing brace by brace-depth counting and
    /// returns (ClassName, ClosingBraceLineIndex).
    /// </summary>
    private static (string ClassName, int ClosingLine) ParseClassBlock(string[] lines, int startLine)
    {
        var firstLine = lines[startLine].TrimStart();
        var classKw = firstLine.IndexOf("class ", StringComparison.Ordinal);
        if (classKw < 0)
            throw new InvalidOperationException(
                $"Expected 'class' keyword on line {startLine + 1} but did not find it: '{lines[startLine]}'.");

        var afterClass = firstLine[(classKw + "class ".Length)..];
        // Class name terminates at whitespace, '{', '<' (generic), or ':' (base list).
        var endIdx = afterClass.AsSpan().IndexOfAny(sr_classNameTerminators);
        var className = endIdx >= 0 ? afterClass[..endIdx] : afterClass;
        className = className.Trim();

        // Find the class's opening brace, then count.
        var depth = 0;
        var seenOpen = false;

        for (var k = startLine; k < lines.Length; k++)
        {
            foreach (var ch in lines[k])
            {
                if (ch == '{')
                {
                    depth++;
                    seenOpen = true;
                }
                else if (ch == '}')
                {
                    depth--;
                    if (seenOpen && depth == 0)
                        return (className, k);
                }
            }
        }

        throw new InvalidOperationException(
            $"Malformed input: class '{className}' starting on line {startLine + 1} has no matching closing brace.");
    }

    private static string ComposeFile(ParsedBlock block)
    {
        // Header matches the combined-file header exactly so xmldoc/auto-gen
        // semantics carry over per-file. Trailing newline keeps editors happy.
        // Use LF — git's autocrlf setting will translate on Windows checkout
        // if configured; deterministic line endings in the file content itself.
        var sb = new System.Text.StringBuilder();
        sb.Append("// <auto-generated/>\n");
        sb.Append("#nullable enable\n");
        sb.Append('\n');
        sb.Append("namespace ").Append(block.Namespace).Append('\n');
        sb.Append("{\n");
        // ClassBlockText is the class's source as it appeared in the combined
        // file, already indented under the namespace. Strip any trailing
        // carriage returns + ensure trailing newline.
        var classText = block.ClassBlockText.Replace("\r", string.Empty, StringComparison.Ordinal);
        sb.Append(classText);
        if (!classText.EndsWith('\n'))
            sb.Append('\n');
        sb.Append("}\n");
        return sb.ToString();
    }

    private sealed record ParsedBlock(
        string Namespace,
        string NamespaceLastSegment,
        string ClassName,
        string ClassBlockText);
}
