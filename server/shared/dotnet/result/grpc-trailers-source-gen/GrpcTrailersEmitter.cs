namespace D2.Shared.Grpc.Trailers.SourceGen;

using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Text;
using System.Text.RegularExpressions;
using D2.Shared.SourceGen;
using D2.Shared.SourceGen.Polyfills;

/// <summary>
/// Pure logic for emitting the <c>D2GrpcTrailers</c> static class source
/// from a parsed <see cref="GrpcTrailersSpec"/>. Stateless and
/// unit-testable in isolation. The Roslyn-host integration
/// (<see cref="GrpcTrailersGenerator"/>) calls this and translates emit-side
/// <see cref="EmitDiagnostic"/> records into Roslyn <c>Diagnostic</c>
/// instances.
/// </summary>
internal static class GrpcTrailersEmitter
{
    /// <summary>The namespace the <c>D2GrpcTrailers</c> static class lives in.</summary>
    public const string ROOT_NAMESPACE = "D2.Shared.Auth.Grpc.Status";

    /// <summary>The emitted class name.</summary>
    public const string CLASS_NAME = "D2GrpcTrailers";

    private static readonly Regex sr_constNameRegex = new(
        "^[A-Z][A-Z0-9_]*$",
        RegexOptions.Compiled,
        TimeSpan.FromMilliseconds(50));

    /// <summary>
    /// Emits the <c>D2GrpcTrailers</c> class source plus diagnostics for
    /// the supplied spec.
    /// </summary>
    /// <param name="spec">Parsed grpc-trailers spec.</param>
    /// <returns>Generated source + diagnostics.</returns>
    public static EmitResult Emit(GrpcTrailersSpec spec)
    {
        var diagnostics = ImmutableArray.CreateBuilder<EmitDiagnostic>();

        var validEntries = new List<GrpcTrailerEntry>();
        var seenConstNames = new HashSet<string>(StringComparer.Ordinal);
        var seenValues = new HashSet<string>(StringComparer.Ordinal);

        foreach (var entry in spec.Trailers)
        {
            if (!sr_constNameRegex.IsMatch(entry.ConstName))
            {
                diagnostics.Add(EmitDiagnostics.InvalidConstName(entry.ConstName));
                continue;
            }

            if (entry.Value.Falsey())
            {
                diagnostics.Add(EmitDiagnostics.EmptyValue(entry.ConstName));
                continue;
            }

            if (!seenConstNames.Add(entry.ConstName))
            {
                diagnostics.Add(EmitDiagnostics.DuplicateConstName(entry.ConstName));
                continue;
            }

            if (!seenValues.Add(entry.Value))
            {
                diagnostics.Add(EmitDiagnostics.DuplicateValue(entry.Value));
                continue;
            }

            validEntries.Add(entry);
        }

        var source = EmitSource(validEntries);
        return new EmitResult(source, diagnostics.ToImmutable());
    }

    private static string EmitSource(List<GrpcTrailerEntry> entries)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// -----------------------------------------------------------------------");
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine(
            "//   Generated by D2.Shared.Grpc.Trailers.SourceGen.GrpcTrailersGenerator");
        sb.AppendLine(
            "//   from contracts/grpc-trailers/grpc-trailers.spec.json (the source");
        sb.AppendLine("//   of truth). Manual edits will be lost on rebuild.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("// -----------------------------------------------------------------------");
        sb.AppendLine();
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine();
        sb.AppendLine($"namespace {ROOT_NAMESPACE};");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine(
            "/// Spec-derived gRPC trailer-key constants. Every gRPC server / client");
        sb.AppendLine(
            "/// references these constants for the trailer Metadata keys instead of");
        sb.AppendLine(
            "/// inline string literals — drift between the wire and the code is");
        sb.AppendLine("/// structurally impossible.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("/// <remarks>");
        sb.AppendLine(
            "/// Cross-language parity: the SAME spec drives the TS-side");
        sb.AppendLine(
            "/// <c>@d2/grpc-client</c> catalog via <c>tools/ts-codegen</c>. Both");
        sb.AppendLine(
            "/// sides emit the same wire keys byte-for-byte; cross-language wire");
        sb.AppendLine("/// drift is impossible.");
        sb.AppendLine("/// </remarks>");
        sb.AppendLine($"public static class {CLASS_NAME}");
        sb.AppendLine("{");

        var first = true;
        foreach (var entry in entries)
        {
            if (!first)
                sb.AppendLine();
            first = false;
            sb.AppendLine($"    /// <summary>{EscapeXmlDoc(entry.Doc)}</summary>");
            sb.AppendLine(
                $"    public const string {entry.ConstName} = "
                    + $"\"{EscapeStringLiteral(entry.Value)}\";");
        }

        if (entries.Count > 0)
            sb.AppendLine();

        EmitAllTrailers(sb, entries);

        sb.AppendLine("}");
        return sb.ToString().LfNormalized();
    }

    private static void EmitAllTrailers(StringBuilder sb, List<GrpcTrailerEntry> entries)
    {
        sb.AppendLine("    /// <summary>");
        sb.AppendLine(
            "    /// All declared trailer wire-keys in spec order. Useful for");
        sb.AppendLine(
            "    /// cross-spec consistency tests and bulk header inspection.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine(
            "    public static IReadOnlyList<string> AllTrailers => sr_allTrailers;");
        sb.AppendLine();
        sb.AppendLine(
            "    private static readonly IReadOnlyList<string> sr_allTrailers = new string[]");
        sb.AppendLine("    {");
        foreach (var entry in entries)
            sb.AppendLine($"        \"{EscapeStringLiteral(entry.Value)}\",");

        sb.AppendLine("    };");
    }

    private static string EscapeStringLiteral(string value) => value
        .Replace("\\", "\\\\")
        .Replace("\"", "\\\"");

    private static string EscapeXmlDoc(string value) => value
        .Replace("&", "&amp;")
        .Replace("<", "&lt;")
        .Replace(">", "&gt;");
}
