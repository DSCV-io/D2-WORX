// Direct-unit tests for emitCsharpDtos.
// Covers: scalar params, empty input (parameterless record), collection of
// nested model, redacted fields (with [property:] target), no-redact ops,
// banner presence, American-English check, nested model emitted once.

import { describe, it, expect } from "vitest";
import { emitCsharpDtos } from "../src/lib/csharp-dto-emitter.js";
import type {
  FieldInfo,
  NestedEnum,
  NestedModel,
} from "../src/lib/model-walk.js";

const TEST_NAMESPACE = "D2.Test.Application";
const TEST_SPEC = "contracts/typespec/test.tsp";

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function field(
  name: string,
  csType: string,
  tsType: string,
  optional = false,
  redactReason?: string,
  jsonName?: string,
): FieldInfo {
  return {
    name,
    csName: name[0]!.toUpperCase() + name.slice(1),
    csType,
    tsName: name,
    tsType,
    optional,
    redactReason,
    jsonName,
    repeated: false,
  };
}

function enumField(name: string, enumRef: NestedEnum): FieldInfo {
  return {
    name,
    csName: name[0]!.toUpperCase() + name.slice(1),
    csType: enumRef.name,
    tsName: name,
    tsType: enumRef.name,
    protoType: "string",
    optional: false,
    redactReason: undefined,
    repeated: false,
    enumRef,
  };
}

function nested(name: string, fields: FieldInfo[]): NestedModel {
  return { name, fields };
}

