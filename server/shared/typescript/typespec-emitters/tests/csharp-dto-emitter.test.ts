describe("emitCsharpDtos_ScalarInput_PositionalRecord", () => {
  it("emits positional sealed record with scalar params and banner", () => {
    const input = [
      field("kid", "string", "string"),
      field("count", "int", "number"),
    ];
    const [inputFile] = emitCsharpDtos(
      "rotateKey",
      TEST_NAMESPACE,
      TEST_SPEC,
      input,
      [],
      [],
    );

    expect(inputFile!.fileName).toBe("RotateKeyInput.g.cs");
    expect(inputFile!.content).toContain("// <auto-generated>");
    expect(inputFile!.content).toContain(`Source spec: ${TEST_SPEC}`);
    expect(inputFile!.content).toContain(
      "public sealed record RotateKeyInput(",
    );
    expect(inputFile!.content).toContain("string Kid");
    expect(inputFile!.content).toContain("int Count");
    expect(inputFile!.content).toContain("#nullable enable");
    expect(inputFile!.content).toContain(`namespace ${TEST_NAMESPACE};`);
  });
});

describe("emitCsharpDtos_EmptyInput_ParameterlessRecord", () => {
  it("emits parameterless sealed record for op with no input params", () => {
    const [inputFile] = emitCsharpDtos(
      "getJwks",
      TEST_NAMESPACE,
      TEST_SPEC,
      [],
      [],
      [],
    );

    expect(inputFile!.fileName).toBe("GetJwksInput.g.cs");
    // Parameterless record ends with semicolon — no parentheses.
    expect(inputFile!.content).toContain("public sealed record GetJwksInput;");
    expect(inputFile!.content).not.toContain("GetJwksInput(");
  });
});

describe("emitCsharpDtos_OutputWithNestedCollection", () => {
  it("emits IReadOnlyList<Jwk> and the Jwk nested record", () => {
    const jwkFields = [
      field("kid", "string", "string"),
      field("n", "string", "string"),
      field("e", "string", "string"),
    ];
    const outputFields = [
      field("keys", "IReadOnlyList<Jwk>", "readonly Jwk[]"),
    ];
    const [, outputFile] = emitCsharpDtos(
      "getJwks",
      TEST_NAMESPACE,
      TEST_SPEC,
      [],
      outputFields,
      [nested("Jwk", jwkFields)],
    );

    expect(outputFile!.content).toContain("IReadOnlyList<Jwk> Keys");
    expect(outputFile!.content).toContain("public sealed record Jwk(");
    expect(outputFile!.content).toContain("string Kid");
    expect(outputFile!.content).toContain("string N");
    expect(outputFile!.content).toContain("string E");
  });
});

describe("emitCsharpDtos_RedactedField_PropertyTarget", () => {
  it("emits [property: RedactData] on redacted param and adds using directives", () => {
    const inputFields = [
      field("kid", "string", "string"),
      field("payload", "byte[]", "Uint8Array", false, "SecretInformation"), // redacted
    ];
    const [inputFile] = emitCsharpDtos(
      "sign",
      TEST_NAMESPACE,
      TEST_SPEC,
      inputFields,
      [],
      [],
    );

    // The [property:] attribute target is mandatory — a bare param attribute
    // would NOT be seen by the property-reflecting RedactDataDestructuringPolicy.
    expect(inputFile!.content).toContain(
      "[property: RedactData(Reason = RedactReason.SecretInformation)] byte[] Payload",
    );
    expect(inputFile!.content).toContain(
      "using D2.Shared.Utilities.Attributes;",
    );
    expect(inputFile!.content).toContain("using D2.Shared.Utilities.Enums;");
    // Non-redacted field has no attribute.
    expect(inputFile!.content).toContain("string Kid");
    expect(inputFile!.content).not.toContain("string Kid\n    [property:");
  });

  it("non-redacted op emits NO using directives for RedactData", () => {
    const inputFields = [field("id", "string", "string")];
    const [inputFile] = emitCsharpDtos(
      "noRedact",
      TEST_NAMESPACE,
      TEST_SPEC,
      inputFields,
      [],
      [],
    );

    expect(inputFile!.content).not.toContain(
      "using D2.Shared.Utilities.Attributes;",
    );
    expect(inputFile!.content).not.toContain(
      "using D2.Shared.Utilities.Enums;",
    );
    expect(inputFile!.content).not.toContain("RedactData");
  });
});

describe("emitCsharpDtos_RedactedField_ReasonThreadedFailLoud", () => {
  it("emits the exact threaded RedactReason, never a hard-coded default", () => {
    const inputFields = [
      field("token", "string", "string", false, "FinancialInformation"),
    ];
    const [inputFile] = emitCsharpDtos(
      "store",
      TEST_NAMESPACE,
      TEST_SPEC,
      inputFields,
      [],
      [],
    );

    expect(inputFile!.content).toContain(
      "[property: RedactData(Reason = RedactReason.FinancialInformation)] string Token",
    );
    // The reason is threaded from @d2Redact — never defaulted to PersonalInformation.
    expect(inputFile!.content).not.toContain("PersonalInformation");
  });

  it("fails loud when a redacted field carries an unrecognized RedactReason", () => {
    const inputFields = [
      field("payload", "byte[]", "Uint8Array", false, "NotARealReason"),
    ];

    expect(() =>
      emitCsharpDtos("sign", TEST_NAMESPACE, TEST_SPEC, inputFields, [], []),
    ).toThrow(/RedactReason/);
  });
});

describe("emitCsharpDtos_JsonPropertyName_WireOverride", () => {
  it("jsonName set (differs from default) → [property: JsonPropertyName] + System.Text.Json using", () => {
    // The OIDC discovery doc's snake_case field: a property JwksUri whose JSON
    // wire form must be jwks_uri.
    const outputFields = [
      field("jwksUri", "string", "string", false, undefined, "jwks_uri"),
    ];
    const [, outputFile] = emitCsharpDtos(
      "getOidcConfiguration",
      TEST_NAMESPACE,
      TEST_SPEC,
      [],
      outputFields,
      [],
    );

    expect(outputFile!.content).toContain(
      '[property: JsonPropertyName("jwks_uri")] string JwksUri',
    );
    expect(outputFile!.content).toContain(
      "using System.Text.Json.Serialization;",
    );
  });

  it("no jsonName + no enums → attribute absent AND the System.Text.Json using absent (byte-stability guard)", () => {
    const outputFields = [field("issuer", "string", "string")];
    const [, outputFile] = emitCsharpDtos(
      "getOidcConfiguration",
      TEST_NAMESPACE,
      TEST_SPEC,
      [],
      outputFields,
      [],
    );

    expect(outputFile!.content).not.toContain("JsonPropertyName");
    expect(outputFile!.content).not.toContain(
      "using System.Text.Json.Serialization;",
    );
  });

  it("jsonName + redact on the same field → BOTH attributes, JsonPropertyName first", () => {
    const outputFields = [
      field(
        "secretWire",
        "string",
        "string",
        false,
        "SecretInformation",
        "secret_wire",
      ),
    ];
    const [, outputFile] = emitCsharpDtos(
      "combo",
      TEST_NAMESPACE,
      TEST_SPEC,
      [],
      outputFields,
      [],
    );

    expect(outputFile!.content).toContain(
      '[property: JsonPropertyName("secret_wire")] [property: RedactData(Reason = RedactReason.SecretInformation)] string SecretWire',
    );
    // Both namespaces are present.
    expect(outputFile!.content).toContain(
      "using System.Text.Json.Serialization;",
    );
    expect(outputFile!.content).toContain(
      "using D2.Shared.Utilities.Attributes;",
    );
  });

  it("jsonName on an array field → [property: JsonPropertyName] precedes the IReadOnlyList type", () => {
    const outputFields: FieldInfo[] = [
      {
        name: "idTokenSigningAlgValuesSupported",
        csName: "IdTokenSigningAlgValuesSupported",
        csType: "IReadOnlyList<string>",
        tsName: "idTokenSigningAlgValuesSupported",
        tsType: "readonly string[]",
        protoType: "string",
        optional: false,
        redactReason: undefined,
        jsonName: "id_token_signing_alg_values_supported",
        repeated: true,
      },
    ];
    const [, outputFile] = emitCsharpDtos(
      "getOidcConfiguration",
      TEST_NAMESPACE,
      TEST_SPEC,
      [],
      outputFields,
      [],
    );

    expect(outputFile!.content).toContain(
      '[property: JsonPropertyName("id_token_signing_alg_values_supported")] IReadOnlyList<string> IdTokenSigningAlgValuesSupported',
    );
  });

  it("jsonName on a nested-model field → the System.Text.Json using is added for the owning record", () => {
    const nestedWithJsonName = nested("Inner", [
      field("wireField", "string", "string", false, undefined, "wire_field"),
    ]);
    const [, outputFile] = emitCsharpDtos(
      "withNested",
      TEST_NAMESPACE,
      TEST_SPEC,
      [],
      [field("inner", "Inner", "Inner")],
      [nestedWithJsonName],
    );

    expect(outputFile!.content).toContain(
      "using System.Text.Json.Serialization;",
    );
    expect(outputFile!.content).toContain(
      '[property: JsonPropertyName("wire_field")] string WireField',
    );
  });
});

describe("emitCsharpDtos_BannerAndAutoGenerated", () => {
  it("every emitted file starts with the auto-generated banner", () => {
    const [inputFile, outputFile] = emitCsharpDtos(
      "testOp",
      TEST_NAMESPACE,
      TEST_SPEC,
      [field("x", "string", "string")],
      [field("y", "int", "number")],
      [],
    );

    for (const f of [inputFile!, outputFile!]) {
      expect(f.content).toContain("// <auto-generated>");
      // The banner indents the body lines with spaces (see buildBanner).
      expect(f.content).toContain(
        "//   Generated by the @d2/typespec-emitters TypeSpec emitter.",
      );
      expect(f.content).toContain("//   Manual edits will be lost on rebuild.");
      // No copyright-file header (that is for hand-authored files only).
      expect(f.content).not.toContain("<copyright file=");
    }
  });
});

