const NS = "D2.Edge.Tests.TypeSpecRoute.Generated";
const SOURCE = "contracts/typespec/fixtures/sign-shaped.tsp";

function makeBaseRouteInput(
  overrides: Partial<RoutePolicyEmitInput> = {},
): RoutePolicyEmitInput {
  return {
    opName: "signFixture",
    verb: "post",
    routePath: "/internal/v1/fixtures/sign-fixture",
    delegationTarget: {
      kind: "facade",
      typeName: "ISignFixtureSignerFacade",
      methodName: "SignFixtureAsync",
    },
    delegationTargetNamespace: "D2.Edge.Tests.TypeSpecRoute.Generated.Facade",
    inputTypeName: "SignFixtureInput",
    outputTypeName: "SignFixtureOutput",
    dtoNamespace: "D2.Edge.Tests.TypeSpecDto.Generated",
    scopePolicy: { kind: "any", scopes: ["self.write"] },
    rateTier: "Standard",
    csrf: "exempt",
    registrationNamespace: NS,
    sourceSpec: SOURCE,
    ...overrides,
  };
}

function makeHeaderGateInput(
  overrides: Partial<IdempotencyGateInput> = {},
): IdempotencyGateInput {
  return {
    keySource: "header",
    ttlSeconds: 86400,
    fields: [],
    inputTypeName: "SignFixtureInput",
    outputTypeName: "SignFixtureOutput",
    pascalOpName: "SignFixture",
    ...overrides,
  };
}

function makeDerivedGateInput(
  overrides: Partial<IdempotencyGateInput> = {},
): IdempotencyGateInput {
  return {
    keySource: "derived",
    ttlSeconds: 3600,
    fields: ["Kid"],
    inputTypeName: "SignFixtureInput",
    outputTypeName: "SignFixtureOutput",
    pascalOpName: "SignDerived",
    ...overrides,
  };
}

