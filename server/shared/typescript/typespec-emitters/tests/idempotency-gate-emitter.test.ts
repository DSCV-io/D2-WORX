describe("buildIdempotencyGate — adversarial inputs", () => {
  it("unknown keySource throws loudly (not silent empty emit)", () => {
    expect(() =>
      buildIdempotencyGate({
        keySource: "cookie" as "header" | "derived",
        ttlSeconds: 100,
        fields: [],
        inputTypeName: "Foo",
        outputTypeName: "FooOutput",
        pascalOpName: "Foo",
      }),
    ).toThrow("unknown keySource 'cookie'");
  });

  it("derived keySource with empty fields array throws loudly", () => {
    expect(() =>
      buildIdempotencyGate({
        keySource: "derived",
        ttlSeconds: 100,
        fields: [],
        inputTypeName: "Foo",
        outputTypeName: "FooOutput",
        pascalOpName: "Foo",
      }),
    ).toThrow("derived keySource requires at least one field name");
  });

  it("derived keySource with an empty field name throws loudly", () => {
    expect(() =>
      buildIdempotencyGate({
        keySource: "derived",
        ttlSeconds: 100,
        fields: [""],
        inputTypeName: "Foo",
        outputTypeName: "FooOutput",
        pascalOpName: "Foo",
      }),
    ).toThrow("field name must not be empty");
  });

  it("header keySource with zero ttlSeconds emits as-is (decorator validates; emitter trusts)", () => {
    // The decorator layer guarantees ttl > 0; the emitter reads it defensively
    // (emits whatever it is given, no silent default substitution).
    const weave = buildIdempotencyGate(makeHeaderGateInput({ ttlSeconds: 0 }));
    expect(weave.postDelegateLines.join("\n")).toContain(
      "TimeSpan.FromSeconds(0)",
    );
  });

  it("derived keySource with many fields produces a hash over all of them", () => {
    const weave = buildIdempotencyGate(
      makeDerivedGateInput({ fields: ["A", "B", "C", "D"] }),
    );
    const pre = weave.preDelegateLines.join("\n");
    expect(pre).toContain("input.A");
    expect(pre).toContain("input.B");
    expect(pre).toContain("input.C");
    expect(pre).toContain("input.D");
  });
});

