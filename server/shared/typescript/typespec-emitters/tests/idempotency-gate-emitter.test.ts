describe("buildIdempotencyGate — header keySource", () => {
  it("storeParam is 'D2GeneratedIdempotencyStore store'", () => {
    const weave = buildIdempotencyGate(makeHeaderGateInput());
    expect(weave.storeParam).toBe("D2GeneratedIdempotencyStore store");
  });

  it("preDelegateLines include header read from Idempotency-Key", () => {
    const weave = buildIdempotencyGate(makeHeaderGateInput());
    const pre = weave.preDelegateLines.join("\n");
    expect(pre).toContain('"Idempotency-Key"');
  });

  it("preDelegateLines include Falsey() guard for null/empty/whitespace", () => {
    const weave = buildIdempotencyGate(makeHeaderGateInput());
    const pre = weave.preDelegateLines.join("\n");
    expect(pre).toContain(".Falsey()");
  });

  it("preDelegateLines include ValidationFailed return when key is absent/whitespace", () => {
    const weave = buildIdempotencyGate(makeHeaderGateInput());
    const pre = weave.preDelegateLines.join("\n");
    expect(pre).toContain("ValidationFailed()");
    expect(pre).toContain("statusCode: 400");
    expect(pre).toContain("application/problem+json");
  });

  it("preDelegateLines include TryGetAsync replay-check", () => {
    const weave = buildIdempotencyGate(makeHeaderGateInput());
    const pre = weave.preDelegateLines.join("\n");
    expect(pre).toContain("store.TryGetAsync");
    expect(pre).toContain("idempotencyKey");
  });

  it("preDelegateLines include replay short-circuit (return replayed result)", () => {
    const weave = buildIdempotencyGate(makeHeaderGateInput());
    const pre = weave.preDelegateLines.join("\n");
    expect(pre).toContain("cachedResult.Success");
    expect(pre).toContain("replayed");
    expect(pre).toContain("replayStatus = (int)replayed.StatusCode");
    expect(pre).toContain("if (replayStatus < 400)");
    expect(pre).toContain(
      "Results.Json(replayed.Data, statusCode: replayStatus)",
    );
    expect(pre).toContain("ToProblemDetails");
  });

  it("postDelegateLines include StoreAsync with correct TTL", () => {
    const weave = buildIdempotencyGate(makeHeaderGateInput());
    const post = weave.postDelegateLines.join("\n");
    expect(post).toContain("store.StoreAsync");
    expect(post).toContain("idempotencyKey");
    expect(post).toContain("TimeSpan.FromSeconds(86400)");
  });

  it("extraUsings includes D2.Shared.Utilities.Extensions (for Falsey)", () => {
    const weave = buildIdempotencyGate(makeHeaderGateInput());
    expect(weave.extraUsings).toContain("D2.Shared.Utilities.Extensions");
  });

  it("replay-check appears BEFORE postDelegateLines (order: pre → delegate → post)", () => {
    // preDelegateLines must contain replay; postDelegateLines must contain store.
    const weave = buildIdempotencyGate(makeHeaderGateInput());
    const preCombined = weave.preDelegateLines.join("\n");
    const postCombined = weave.postDelegateLines.join("\n");
    expect(preCombined).toContain("TryGetAsync");
    expect(postCombined).toContain("StoreAsync");
    // StoreAsync must NOT appear in pre (it must be after the delegation call).
    expect(preCombined).not.toContain("StoreAsync");
    // TryGetAsync must NOT appear in post.
    expect(postCombined).not.toContain("TryGetAsync");
  });

  it("different ttlSeconds propagates correctly", () => {
    const weave = buildIdempotencyGate(
      makeHeaderGateInput({ ttlSeconds: 3600 }),
    );
    expect(weave.postDelegateLines.join("\n")).toContain(
      "TimeSpan.FromSeconds(3600)",
    );
  });
});

