describe("emitRoutePolicy — header idempotency gate woven in", () => {
  it("store param appears in the delegate signature (header)", () => {
    const file = emitRoutePolicy(
      makeBaseRouteInput({
        idempotency: { keySource: "header", ttlSeconds: 86400, fields: [] },
      }),
    );
    expect(file.content).toContain("D2GeneratedIdempotencyStore store");
  });

  it("header read appears BEFORE the delegation call", () => {
    const file = emitRoutePolicy(
      makeBaseRouteInput({
        idempotency: { keySource: "header", ttlSeconds: 86400, fields: [] },
      }),
    );
    const headerIdx = file.content.indexOf('"Idempotency-Key"');
    const delegateIdx = file.content.indexOf("facade.SignFixtureAsync");
    expect(headerIdx).toBeGreaterThan(-1);
    expect(delegateIdx).toBeGreaterThan(-1);
    expect(headerIdx).toBeLessThan(delegateIdx);
  });

  it("TryGetAsync replay check appears BEFORE the delegation call", () => {
    const file = emitRoutePolicy(
      makeBaseRouteInput({
        idempotency: { keySource: "header", ttlSeconds: 86400, fields: [] },
      }),
    );
    const tryGetIdx = file.content.indexOf("store.TryGetAsync");
    const delegateIdx = file.content.indexOf("facade.SignFixtureAsync");
    expect(tryGetIdx).toBeGreaterThan(-1);
    expect(tryGetIdx).toBeLessThan(delegateIdx);
  });

  it("StoreAsync call appears AFTER the delegation call", () => {
    const file = emitRoutePolicy(
      makeBaseRouteInput({
        idempotency: { keySource: "header", ttlSeconds: 86400, fields: [] },
      }),
    );
    const storeIdx = file.content.indexOf("store.StoreAsync");
    const delegateIdx = file.content.indexOf("facade.SignFixtureAsync");
    expect(storeIdx).toBeGreaterThan(-1);
    expect(storeIdx).toBeGreaterThan(delegateIdx);
  });

  it("ValidationFailed guard present for absent/whitespace key (header)", () => {
    const file = emitRoutePolicy(
      makeBaseRouteInput({
        idempotency: { keySource: "header", ttlSeconds: 86400, fields: [] },
      }),
    );
    expect(file.content).toContain("ValidationFailed()");
    expect(file.content).toContain(".Falsey()");
  });

  it("emits D2.Shared.Utilities.Extensions using (for Falsey)", () => {
    const file = emitRoutePolicy(
      makeBaseRouteInput({
        idempotency: { keySource: "header", ttlSeconds: 86400, fields: [] },
      }),
    );
    expect(file.content).toContain("using D2.Shared.Utilities.Extensions;");
  });

  it("using directives remain sorted after adding gate usings", () => {
    const file = emitRoutePolicy(
      makeBaseRouteInput({
        idempotency: { keySource: "header", ttlSeconds: 86400, fields: [] },
      }),
    );
    const lines = file.content.split("\n");
    const usingLines = lines
      .filter((l) => l.startsWith("using "))
      .map((l) =>
        l
          .replace(/^using /, "")
          .replace(";", "")
          .trim(),
      );
    for (let i = 1; i < usingLines.length; i++)
      expect(
        usingLines[i]!.localeCompare(usingLines[i - 1]!),
      ).toBeGreaterThanOrEqual(0);
  });

  it("MAP-ii success/failure shape is still present AFTER the gate lines", () => {
    const file = emitRoutePolicy(
      makeBaseRouteInput({
        idempotency: { keySource: "header", ttlSeconds: 86400, fields: [] },
      }),
    );
    const storeIdx = file.content.indexOf("store.StoreAsync");
    const statusIdx = file.content.indexOf(
      "var status = (int)result.StatusCode;",
      storeIdx,
    );
    expect(statusIdx).toBeGreaterThan(storeIdx);
    expect(file.content).toContain("if (status < 400)");
    expect(file.content).toContain(
      "Results.Json(result.Data, statusCode: status)",
    );
    expect(file.content).toContain("ToProblemDetails");
  });
});

